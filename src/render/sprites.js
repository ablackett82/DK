// Sprites (16x16, 2 bits per pixel), drawn for this project. Codes are the
// ones the game puts in its sprite list; codes $80-$FF are the same pictures
// mirrored, so only $00-$7F are defined. Kong is several sprites at once: his
// poses are drawn whole below and cut into pieces at the positions the game's
// pose tables use ($385C and friends), so the pieces line up.
//
// Pixels: '.' = transparent, '1'-'3' = colours 1-3 of the sprite's palette.

const W = 16;
const pad = (rows, w = W, h = W) => {
  const out = rows.map((r) => {
    if (r.length > w) throw new Error(`sprite row too long (${r.length}): ${r}`);
    return r.padEnd(w, '.');
  });
  while (out.length < h) out.push('.'.repeat(w));
  if (out.length > h) throw new Error(`sprite too tall: ${out.length}`);
  return out;
};
const mirror = (rows) => rows.map((r) => [...r].reverse().join(''));
const flipV = (rows) => [...rows].reverse();
const recolor = (rows, map) => rows.map((r) => [...r].map((c) => map[c] ?? c).join(''));
/** Cut a 16x16 piece whose top-left is (x, y) out of a picture. */
function cut(pic, x, y) {
  const rows = [];
  for (let j = 0; j < W; j++) {
    let r = '';
    for (let i = 0; i < W; i++) r += pic[y + j]?.[x + i] ?? '.';
    rows.push(r.replace(/[^123]/g, '.'));
  }
  return rows;
}
/** A picture from its left half, mirrored to make the right. */
const symmetric = (half) => half.map((r) => r + [...r].reverse().join(''));

export const SPRITES = {};
const put = (code, rows) => { SPRITES[code] = pad(rows); };

